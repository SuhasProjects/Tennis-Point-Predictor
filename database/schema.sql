-- PostgreSQL 18-compatible telemetry schema.
-- The application creates the same tables automatically through SQLAlchemy.

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT REFERENCES matches(id) ON DELETE SET NULL,
    source_path VARCHAR(2048) NOT NULL,
    fps DOUBLE PRECISION NOT NULL CHECK (fps > 0),
    width INTEGER NOT NULL CHECK (width > 0),
    height INTEGER NOT NULL CHECK (height > 0),
    total_frames INTEGER NOT NULL CHECK (total_frames >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS frames (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    frame_index INTEGER NOT NULL CHECK (frame_index >= 0),
    timestamp_ms DOUBLE PRECISION NOT NULL CHECK (timestamp_ms >= 0),
    homography JSONB,
    court_reprojection_error DOUBLE PRECISION,
    court_inlier_count INTEGER NOT NULL DEFAULT 0,
    court_stale_frames INTEGER NOT NULL DEFAULT 0,
    court_detected BOOLEAN NOT NULL DEFAULT FALSE,
    scene_cut BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_frames_video_frame UNIQUE (video_id, frame_index)
);

CREATE TABLE IF NOT EXISTS player_detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    frame_id BIGINT NOT NULL REFERENCES frames(id) ON DELETE CASCADE,
    player_id VARCHAR(8) NOT NULL CHECK (player_id IN ('near', 'far')),
    confidence DOUBLE PRECISION NOT NULL,
    selection_score DOUBLE PRECISION NOT NULL,
    bbox JSONB NOT NULL,
    foot_image JSONB NOT NULL,
    court_x DOUBLE PRECISION,
    court_y DOUBLE PRECISION,
    keypoints JSONB NOT NULL,
    CONSTRAINT uq_player_detections_frame_player UNIQUE (frame_id, player_id)
);

CREATE INDEX IF NOT EXISTS ix_frames_video_timestamp ON frames(video_id, timestamp_ms);
CREATE INDEX IF NOT EXISTS ix_player_detections_frame ON player_detections(frame_id);
CREATE INDEX IF NOT EXISTS ix_player_detections_identity ON player_detections(player_id, frame_id);
